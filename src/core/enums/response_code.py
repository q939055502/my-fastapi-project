from enum import IntEnum


# 响应码枚举，具体响应消息在response/response_msg.yaml中配置
class ResponseCode(IntEnum):
    # 200 开头：业务成功/失败
    SUCCESS = 20000
    DATA_NOT_EXIST = 20001
    DATA_ALREADY_EXIST = 20002
    STATUS_ABNORMAL = 20003
    RESOURCE_INSUFFICIENT = 20004
    BUSINESS_CONDITION_NOT_SATISFIED = 20005

    # 400 开头：参数错误
    PARAM_ERROR = 40000
    PARAM_REQUIRED = 40001
    PARAM_FORMAT_INVALID = 40002
    PARAM_LENGTH_EXCEEDED = 40003
    PARAM_VALUE_INVALID = 40004

    # 401 开头：鉴权
    UNAUTHORIZED = 40100
    TOKEN_FORMAT_INVALID = 40101
    TOKEN_EXPIRED = 40102
    TOKEN_REVOKED = 40103

    # 403 开头：权限
    FORBIDDEN = 40300
    ACCOUNT_DISABLED = 40301
    TENANT_EXPIRED = 40302
    API_PERMISSION_NOT_GRANTED = 40303

    # 404 开头：不存在
    NOT_FOUND = 40400
    ENTITY_NOT_FOUND = 40401

    # 422 开头：参数校验失败
    VALIDATION_ERROR = 42200
    VALIDATION_REQUIRED = 42201
    VALIDATION_TYPE_ERROR = 42202
    VALIDATION_FORMAT_ERROR = 42203

    # 429 开头：限流
    RATE_LIMIT_EXCEEDED = 42900
    ACCOUNT_RATE_LIMIT_EXCEEDED = 42901

    # 500 开头：服务端
    SERVER_ERROR = 50000
    DATABASE_ERROR = 50001
    THIRD_PARTY_ERROR = 50002
